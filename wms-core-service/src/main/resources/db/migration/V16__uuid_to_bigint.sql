-- =====================================================================
-- V16: UUID → BIGINT primary key / foreign key migration
-- PostgreSQL 16 — wms_core_db
--
-- Converts all UUID PK/FK columns listed below to BIGINT while preserving
-- row data and relationships via id_legacy_map.
-- =====================================================================

BEGIN;

-- -----------------------------------------------------------------------
-- Legacy UUID → BIGINT mapping table
-- -----------------------------------------------------------------------
CREATE TABLE id_legacy_map (
    entity_type VARCHAR(50) NOT NULL,
    old_uuid    UUID        NOT NULL,
    new_id      BIGINT      NOT NULL,
    PRIMARY KEY (entity_type, old_uuid)
);

CREATE INDEX idx_id_legacy_map_new_id ON id_legacy_map (entity_type, new_id);

-- -----------------------------------------------------------------------
-- Helper: populate id_bigint + id_legacy_map for a table PK
-- -----------------------------------------------------------------------
CREATE OR REPLACE FUNCTION wms_migrate_uuid_pk(
    p_table       TEXT,
    p_entity_type VARCHAR(50),
    p_order_by    TEXT
) RETURNS void
LANGUAGE plpgsql
AS $$
BEGIN
    EXECUTE format(
        'ALTER TABLE %I ADD COLUMN id_bigint BIGINT',
        p_table
    );

    EXECUTE format(
        'UPDATE %I t
            SET id_bigint = ranked.new_id
           FROM (
               SELECT id AS old_id,
                      ROW_NUMBER() OVER (ORDER BY %s) AS new_id
                 FROM %I
           ) ranked
          WHERE t.id = ranked.old_id',
        p_table, p_order_by, p_table
    );

    EXECUTE format(
        'INSERT INTO id_legacy_map (entity_type, old_uuid, new_id)
         SELECT %L, id, id_bigint FROM %I',
        p_entity_type, p_table
    );
END;
$$;

-- -----------------------------------------------------------------------
-- Helper: add/populate a FK column from id_legacy_map
-- -----------------------------------------------------------------------
CREATE OR REPLACE FUNCTION wms_migrate_uuid_fk(
    p_table       TEXT,
    p_column      TEXT,
    p_entity_type VARCHAR(50)
) RETURNS void
LANGUAGE plpgsql
AS $$
BEGIN
    EXECUTE format(
        'ALTER TABLE %I ADD COLUMN %I BIGINT',
        p_table, p_column || '_bigint'
    );

    EXECUTE format(
        'UPDATE %I t
            SET %I = m.new_id
           FROM id_legacy_map m
          WHERE m.entity_type = %L
            AND m.old_uuid = t.%I',
        p_table, p_column || '_bigint', p_entity_type, p_column
    );
END;
$$;

-- -----------------------------------------------------------------------
-- Helper: finalize PK — drop UUID id, promote id_bigint, add IDENTITY
-- -----------------------------------------------------------------------
CREATE OR REPLACE FUNCTION wms_finalize_uuid_pk(p_table TEXT)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    v_max_id BIGINT;
BEGIN
    EXECUTE format(
        'ALTER TABLE %I DROP CONSTRAINT IF EXISTS %I',
        p_table, p_table || '_pkey'
    );
    EXECUTE format('ALTER TABLE %I DROP COLUMN id', p_table);
    EXECUTE format('ALTER TABLE %I RENAME COLUMN id_bigint TO id', p_table);
    EXECUTE format('ALTER TABLE %I ALTER COLUMN id SET NOT NULL', p_table);
    EXECUTE format('ALTER TABLE %I ADD PRIMARY KEY (id)', p_table);
    EXECUTE format(
        'ALTER TABLE %I ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY',
        p_table
    );

    EXECUTE format('SELECT COALESCE(MAX(id), 0) FROM %I', p_table) INTO v_max_id;
    IF v_max_id > 0 THEN
        PERFORM setval(pg_get_serial_sequence(p_table, 'id'), v_max_id);
    END IF;
END;
$$;

-- -----------------------------------------------------------------------
-- Helper: finalize FK — drop UUID column, promote *_bigint column
-- -----------------------------------------------------------------------
CREATE OR REPLACE FUNCTION wms_finalize_uuid_fk(p_table TEXT, p_column TEXT)
RETURNS void
LANGUAGE plpgsql
AS $$
BEGIN
    EXECUTE format('ALTER TABLE %I DROP COLUMN %I', p_table, p_column);
    EXECUTE format(
        'ALTER TABLE %I RENAME COLUMN %I TO %I',
        p_table, p_column || '_bigint', p_column
    );
END;
$$;

