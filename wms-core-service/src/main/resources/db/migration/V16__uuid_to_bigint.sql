-- PHASE 3 — Integrity checks before destructive DDL
-- ===================================================================

DO $$
DECLARE
    v_unmapped_entity_ids BIGINT;
BEGIN
    SELECT COUNT(*) INTO v_unmapped_entity_ids
      FROM configuration_audit_logs
     WHERE entity_id_bigint IS NULL;

    IF v_unmapped_entity_ids > 0 THEN
        RAISE EXCEPTION
            'configuration_audit_logs: % row(s) have unmapped entity_id (unknown entity_name)',
            v_unmapped_entity_ids;
    END IF;

    IF EXISTS (
        SELECT 1
          FROM companies
         WHERE organization_id IS NOT NULL
           AND organization_id_bigint IS NULL
    ) THEN
        RAISE EXCEPTION 'companies.organization_id has unmapped UUID values';
    END IF;
END;
$$;

