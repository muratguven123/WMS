CREATE TABLE notification_template
(
    id            BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    template_code VARCHAR(100) NOT NULL,
    channel       VARCHAR(20)  NOT NULL,
    description   TEXT,
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ,
    created_by    VARCHAR(255),
    updated_by    VARCHAR(255),

    CONSTRAINT pk_notification_template PRIMARY KEY (id),
    CONSTRAINT uq_notification_template_code UNIQUE (template_code),
    CONSTRAINT chk_notification_template_channel CHECK (channel IN ('EMAIL', 'SMS', 'PUSH'))
);

CREATE INDEX idx_notification_template_code    ON notification_template (template_code);
CREATE INDEX idx_notification_template_channel ON notification_template (channel);
CREATE INDEX idx_notification_template_active  ON notification_template (active);

