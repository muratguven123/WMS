-- -----------------------------------------------------------------------------
-- 3. missing_template_log
--    İstenen dilde içeriği bulunamayan şablon kayıtları
--    (missing_translation_log ile aynı desen).
-- -----------------------------------------------------------------------------
CREATE TABLE missing_template_log
(
    id            BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    locale        VARCHAR(10)  NOT NULL,
    template_code VARCHAR(100) NOT NULL,
    channel       VARCHAR(20),
    first_seen_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    last_seen_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    hit_count     BIGINT       NOT NULL DEFAULT 1,
    resolved      BOOLEAN      NOT NULL DEFAULT FALSE,
    resolved_at   TIMESTAMPTZ,

    CONSTRAINT pk_missing_template_log PRIMARY KEY (id),
    CONSTRAINT uq_mtpl_locale_template UNIQUE (locale, template_code),
    CONSTRAINT chk_mtpl_hit_count CHECK (hit_count >= 1)
);

CREATE INDEX idx_mtpl_template_code ON missing_template_log (template_code);
CREATE INDEX idx_mtpl_locale        ON missing_template_log (locale);
CREATE INDEX idx_mtpl_resolved      ON missing_template_log (resolved);
CREATE INDEX idx_mtpl_last_seen     ON missing_template_log (last_seen_at DESC);

-- Admin dashboard için: çözümlenmemiş + en çok hit alan üstte
CREATE INDEX idx_mtpl_unresolved_hits
    ON missing_template_log (resolved, hit_count DESC)
    WHERE resolved = FALSE;

